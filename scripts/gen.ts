// Regenerates what Orca needs to read statically from formats.json:
//   - orca-plugin.json contributes.customEditors (see editorsFor in src/registry.ts)
//   - editor/entries/: files.ts for binary formats, <format id>.ts per text format (text documents
//     carry no file name, so each text entry names its format)
// Run after editing formats.json:  node --experimental-strip-types scripts/gen.ts
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRegistry, editorsFor, type FormatsFile } from '../src/registry.ts'

const root = new URL('../', import.meta.url)
const file = JSON.parse(readFileSync(new URL('formats.json', root), 'utf8')) as FormatsFile
createRegistry(file) // validates: duplicate suffixes, unknown converters, mixed outputs, > 32 suffixes

const editors = editorsFor(file)
const entries = new URL('editor/entries/', root)
mkdirSync(entries, { recursive: true })
const header = '// Generated by scripts/gen.ts from formats.json — do not edit.\n'
const files = new Map<string, string>()
for (const e of editors) {
  const name = e.entry.slice('editor/entries/'.length)
  files.set(name, e.contentKind === 'text' ? `${header}import { boot } from '../app'\n\nboot(${JSON.stringify(e.id)})\n` : `${header}import { boot } from '../app'\n\n// Bytes documents name their suffix, which picks the format.\nboot()\n`)
}
for (const name of readdirSync(entries)) if (!files.has(name)) rmSync(new URL(name, entries))
for (const [name, text] of files) writeFileSync(new URL(name, entries), text)

const manifestUrl = new URL('orca-plugin.json', root)
const manifest = JSON.parse(readFileSync(manifestUrl, 'utf8'))
manifest.contributes = {
  ...manifest.contributes,
  customEditors: editors
}
writeFileSync(manifestUrl, JSON.stringify(manifest, null, 2) + '\n')
console.log(`${editors.length} editors, ${file.formats.length} formats, ${file.formats.reduce((n, f) => n + f.extensions.length, 0)} suffixes`)
